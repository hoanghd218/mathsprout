export function PrimaryButton({ className = '', children, ...rest }) {
  return (
    <button className={`btn-primary ${className}`} {...rest}>
      {children}
    </button>
  );
}

export function SecondaryButton({ className = '', children, ...rest }) {
  return (
    <button className={`btn-secondary ${className}`} {...rest}>
      {children}
    </button>
  );
}

export function ChoiceButton({ selected = false, className = '', children, ...rest }) {
  return (
    <button
      type="button"
      className={`choice-btn ${selected ? 'selected' : ''} ${className}`}
      {...rest}
    >
      {children}
    </button>
  );
}

